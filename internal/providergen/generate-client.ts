import {
  camelize,
  humanize,
  pluralize,
  singularize,
  underscore,
} from "inflection";
import { oas30 } from "openapi3-ts";
import { match } from "ts-pattern";
import type { ClientConfig } from "./schema";
import { assertSchemaObject } from "./types";
import { produce } from "immer";
import { getParametersByOperationId, removeReference } from "./openapi";

export function generateClient({
  doc,
  config,
}: {
  doc: oas30.OpenAPIObject;
  config: ClientConfig;
}) {
  console.log(`Generating client: ${config.name}`);
  let schema = removeReference(doc.components?.schemas?.[config.name]);
  if (!schema) {
    throw new Error(`Cannot find schema: ${config.name} in doc`);
  }

  // Add id to the schema and make it the first property
  schema = produce(schema, (draft) => {
    draft.properties = {
      id: {
        type: "string",
        description: `The ID of the ${humanize(config.name, true)}.`,
        "x-go-jsonapi-tag": "primary",
        "x-go-jsonapi-type": underscore(pluralize(config.name)),
      },
      ...draft.properties,
    };

    draft.required = ["id", ...(draft.required ?? [])];
  });

  return `// Code generated by providergen. DO NOT EDIT.
package apiclient

import (
	"bytes"
	"context"
	"fmt"
	"reflect"

	"github.com/rootlyhq/jsonapi"
	rootly "github.com/rootlyhq/terraform-provider-rootly/v5/schema"
)

${generateModel({
  schema,
  name: camelize(config.name),
  parents: [],
})}

${config.actions?.list?.enabled ? generateListAction({ doc, config }) : ""}

${config.actions?.get?.enabled ? generateGetAction({ doc, config }) : ""}
`;
}

function generateModel({
  schema,
  name,
  parents,
}: {
  schema: oas30.SchemaObject;
  name: string;
  parents: string[];
}) {
  if (!schema.properties) {
    throw new Error(`Schema ${name} does not have properties`);
  }

  const required = new Set(schema.required);

  const fields: string[] = [];
  const children: string[] = [];

  for (const [key, value] of Object.entries(schema.properties)) {
    assertSchemaObject(value);
    const property = {
      required: required.has(key),
      nullable: value.nullable ?? false,
    };

    const structTagParts = [
      value["x-go-jsonapi-tag"] ?? "attr",
      value["x-go-jsonapi-type"] ?? key,
    ];
    if (!property.required) {
      structTagParts.push("omitempty");
    }
    const structTag = `\`jsonapi:"${structTagParts.join(",")}"\``;

    const goType = match(value)
      .with({ type: "string" }, () => "string")
      .with({ type: "boolean" }, () => "bool")
      .with({ type: "integer" }, () => "int64")
      .with({ type: "object" }, () => `${name}${camelize(key)}`)
      .with({ type: "array", items: { type: "string" } }, () => "[]string")
      .with({ type: "array", items: { type: "integer" } }, () => "[]int64")
      .with(
        { type: "array", items: { type: "object" } },
        () => `[]${name}${camelize(key)}Item`,
      )
      .otherwise(() => null);

    if (goType) {
      if (value.description) {
        fields.push(
          value.description
            .split("\n")
            .map((line) => `// ${line}`)
            .join("\n"),
        );
      }

      const actualGoType = property.nullable
        ? `jsonapi.NullableAttr[${goType}]`
        : goType;
      fields.push(`${camelize(key)} ${actualGoType} ${structTag}`);
    } else {
      fields.push(
        `// TODO: Support property ${key} of type ${JSON.stringify(value)}`,
      );
    }

    match(value)
      .with({ type: "object" }, (value) => {
        children.push(
          generateModel({
            schema: value,
            name: `${name}${camelize(key)}`,
            parents: [...parents, key],
          }),
        );
      })
      .with({ type: "array", items: { type: "object" } }, (value) => {
        children.push(
          generateModel({
            schema: value.items as oas30.SchemaObject,
            name: `${name}${camelize(key)}Item`,
            parents: [...parents, key],
          }),
        );
      });
  }

  return `
type ${name} struct {
${fields.join("\n")}
}

${children.join("\n\n")}
`;
}

function generateListAction({
  doc,
  config,
}: {
  doc: oas30.OpenAPIObject;
  config: ClientConfig;
}) {
  const listSchema = removeReference(
    doc.components?.schemas?.[`${config.name}_list`],
  );
  if (!listSchema) {
    throw new Error(`Cannot find schema: ${config.name}_list in doc`);
  }

  const operationId = `list${camelize(pluralize(config.name))}`;
  const { funcArgs, clientArgs, hasNonPathParams } = buildFuncAndClientArgs({
    doc,
    operationId,
  });

  return `
func (c *Client) ${camelize(config.name)}List(${funcArgs.join(", ")}) (*[]${camelize(singularize(config.name))}, error) {
  ${
    hasNonPathParams
      ? `if params == nil {
  params = new(rootly.${camelize(operationId)}Params)
}`
      : ""
  }
  items := []${camelize(config.name)}{}

  for {
		resp, err := c.ClientWithResponses.${camelize(operationId)}WithResponse(${clientArgs.join(", ")})
		if err != nil {
			return nil, err
		} else if resp == nil {
			return nil, fmt.Errorf("empty response")
		}

		rawItems, err := jsonapi.UnmarshalManyPayload(bytes.NewReader(resp.Body), reflect.TypeFor[${camelize(config.name)}]())
		if err != nil {
			return nil, fmt.Errorf("failed to unmarshal response body: %w", err)
		}

		for _, it := range rawItems {
			item, ok := it.(*${camelize(config.name)})
			if !ok {
				return nil, fmt.Errorf("invalid response type")
			}
			items = append(items, *item)
		}

		if resp.ApplicationvndApiJSON200.Meta.NextPage != nil {
			params.PageNumber = new(*resp.ApplicationvndApiJSON200.Meta.NextPage)
		} else {
			break
		}
	}

	return &items, nil
}
`;
}

function generateGetAction({
  doc,
  config,
}: {
  doc: oas30.OpenAPIObject;
  config: ClientConfig;
}) {
  const listSchema = removeReference(doc.components?.schemas?.[config.name]);
  if (!listSchema) {
    throw new Error(`Cannot find schema: ${config.name} in doc`);
  }

  const operationId = `get${camelize(config.name)}`;
  const { funcArgs, clientArgs } = buildFuncAndClientArgs({
    doc,
    operationId,
  });

  return `
func (c *Client) ${camelize(config.name)}Get(${funcArgs.join(", ")}) (*${camelize(config.name)}, error) {
  resp, err := c.ClientWithResponses.${camelize(operationId)}WithResponse(${clientArgs.join(", ")})
  if err != nil {
    return nil, err
  } else if resp == nil {
    return nil, fmt.Errorf("empty response")
  }

  var item ${camelize(config.name)}
  if err := jsonapi.UnmarshalPayload(bytes.NewReader(resp.Body), &item); err != nil {
		return nil, err
	}

	return &item, nil
}
`;
}

function buildFuncAndClientArgs({
  doc,
  operationId,
}: {
  doc: oas30.OpenAPIObject;
  operationId: string;
}) {
  const pathParams = getParametersByOperationId({
    doc,
    operationId,
    onlyLocations: ["path"],
  });
  const nonPathParams = getParametersByOperationId({
    doc,
    operationId,
    excludeLocations: ["path"],
  });
  const hasNonPathParams =
    Array.isArray(nonPathParams) && nonPathParams.length > 0;

  const funcArgs = ["ctx context.Context"];
  const clientArgs = ["ctx"];
  if (pathParams) {
    for (const param of pathParams) {
      funcArgs.push(`${camelize(param.name, true)} string`);
      clientArgs.push(camelize(param.name, true));
    }
  }
  if (hasNonPathParams) {
    funcArgs.push(`params *rootly.${camelize(operationId)}Params`);
    clientArgs.push("params");
  }
  return { funcArgs, clientArgs, hasNonPathParams };
}

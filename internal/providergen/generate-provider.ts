import { camelize } from "inflection";
import type { DataSourceConfig, ResourceConfig } from "./schema";

export function generateProvider({
  dataSources,
  resources,
}: {
  dataSources: DataSourceConfig[];
  resources: ResourceConfig[];
}) {
  return `// Code generated by providergen. DO NOT EDIT.
package provider

import (
	"github.com/hashicorp/terraform-plugin-framework/datasource"
	"github.com/hashicorp/terraform-plugin-framework/resource"
)

var (
	AutoGeneratedResources = []func() resource.Resource{
		${resources.map((config) => `New${camelize(config.name)}Resource,`).join("\n")}
	}

	AutoGeneratedDataSources = []func() datasource.DataSource{
		${dataSources.map((config) => `New${camelize(config.name)}DataSource,`).join("\n")}
	}
)
`;
}

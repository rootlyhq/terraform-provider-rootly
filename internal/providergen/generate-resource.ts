function getSchemas({
  doc,
  config,
}: {
  doc: oas30.OpenAPIObject;
  config: ResolvedResourceConfig;
}) {
  // Read
  const read = removeReference(doc.components?.schemas?.[config.name]);
  if (!read) {
    throw new Error(`Cannot find schema: ${config.name} in doc`);
  }

  // Create
  const createBase = removeReference(
    doc.components?.schemas?.[`new_${config.name}`],
  );
  if (!createBase) {
    throw new Error(`Cannot find schema: new_${config.name} in doc`);
  }

  const createData = removeReference(createBase.properties?.data);
  if (!createData) {
    throw new Error(`Cannot find schema: new_${config.name}.data in doc`);
  }

  const create = removeReference(createData.properties?.attributes);
  if (!create) {
    throw new Error(
      `Cannot find schema: new_${config.name}.data.attributes in doc`,
    );
  }

  // Update
  const updateBase = removeReference(
    doc.components?.schemas?.[`update_${config.name}`],
  );
  if (!updateBase) {
    throw new Error(`Cannot find schema: update_${config.name} in doc`);
  }

  const updateData = removeReference(updateBase.properties?.data);
  if (!updateData) {
    throw new Error(`Cannot find schema: update_${config.name}.data in doc`);
  }

  const update = removeReference(updateData.properties?.attributes);
  if (!update) {
    throw new Error(
      `Cannot find schema: update_${config.name}.data.attributes in doc`,
    );
  }

  // Resolved
  const resolved = resolveSchemas({
    doc,
    config,
    read,
    create,
    update,
  });

  return {
    read,
    create,
    update,
    resolved,
  };
}

function resolveSchemas({
  doc,
  config,
  read,
  create,
  update,
}: {
  doc: oas30.OpenAPIObject;
  config: ResolvedResourceConfig;
  read: oas30.SchemaObject;
  create: oas30.SchemaObject | undefined;
  update: oas30.SchemaObject | undefined;
}): oas30.SchemaObject {
  return match(read)
    .with({ type: "array", items: P.record(P.string, P.any) }, (schema) => ({
      ...schema,
      items: resolveSchemas({
        doc,
        config,
        read: removeReference(schema.items),
        create: removeReference(create?.items),
        update: removeReference(update?.items),
      }),
    }))
    .with(
      { type: "object", properties: P.record(P.string, P.any) },
      (schema) => {
        return {
          ...schema,
          properties: Object.fromEntries(
            Object.entries(schema.properties).map(([key, value]) => {
              return [
                key,
                {
                  ...resolveSchemas({
                    doc,
                    config,
                    read: removeReference(value),
                    create: removeReference(create?.properties?.[key]),
                    update: removeReference(update?.properties?.[key]),
                  }),
                  "x-tf-computed-optional-required":
                    resolveComputedOptionalRequired({
                      doc,
                      config,
                      name: key,
                      read,
                      create,
                      update,
                    }),
                },
              ];
            }),
          ),
        };
      },
    )
    .otherwise((schema) => schema);
}

function resolveComputedOptionalRequired({
  doc,
  config,
  name,
  read,
  create,
  update,
}: {
  doc: oas30.OpenAPIObject;
  config: ResolvedResourceConfig;
  name: string;
  read: oas30.SchemaObject;
  create: oas30.SchemaObject | undefined;
  update: oas30.SchemaObject | undefined;
}): ComputedOptionalRequired {
  const inRead = read.properties && name in read.properties;
  const inCreate = create?.properties && name in create.properties;
  const inUpdate = update?.properties && name in update.properties;
  const reqCreate = create?.required && create.required.includes(name);
  const reqUpdate = update?.required && update.required.includes(name);

  if (reqCreate || reqUpdate) {
    return "required";
  }

  if (inRead && !inCreate && !inUpdate) {
    return "computed";
  }

  if (inCreate || inUpdate) {
    if (inRead) {
      return "computed_optional";
    } else {
      return "optional";
    }
  }

  if (inRead) {
    return "computed";
  }

  throw new Error(
    `Cannot determine computed/optional/required for property ${name}: ${JSON.stringify({ read, create, update })}`,
  );
}

function generateSchemaAttributes({
  parent,
  schema,
}: {
  parent: string | null;
  schema: oas30.SchemaObject;
}) {
  if (!schema.properties) {
    throw new Error(`Schema does not have properties`);
  }

  const lines: string[] = [];

  for (const [key, value] of Object.entries(schema.properties)) {
    assertSchemaObject(value);
    lines.push(
      `"${key}": ${generateSchemaAttribute({ parent, name: key, schema: value })},`,
    );
  }

  return lines.join("\n");
}

function generateSchemaAttribute({
  parent,
  name,
  schema,
}: {
  parent: string | null;
  name: string;
  schema: oas30.SchemaObject;
}) {
  if (!schema.type) {
    throw new Error(`Schema does not have a type`);
  }

  const parts: string[] = [];
  parts.push(`${tfAttributeSchemaType({ schema })}{`);

  const validators: string[] = [];

  if (schema.description) {
    let description = schema.description;
    if (!description.endsWith(".")) {
      description += ".";
    }

    if (schema.enum) {
      description +=
        ` Value must be one of ` +
        schema.enum.map((value) => `\`${value}\``).join(", ") +
        ".";
    }

    parts.push(`MarkdownDescription: ${JSON.stringify(description)},`);
  }

  if (schema.enum) {
    match(schema)
      .with({ type: "string", enum: P.array(P.string) }, (schema) => {
        validators.push(
          `stringvalidator.OneOf(${schema.enum.map((value) => JSON.stringify(value)).join(", ")})`,
        );
      })
      .with({ type: "integer", enum: P.array(P.number) }, (schema) => {
        validators.push(
          `int64validator.OneOf(${schema.enum.map((value) => JSON.stringify(JSON.stringify)).join(", ")})`,
        );
      })
      .exhaustive();
  }

  parts.push(
    ...match(schema["x-tf-computed-optional-required"])
      .with("required", () => ["Required: true,"])
      .with("computed", () => ["Computed: true,"])
      .with("computed_optional", () => ["Optional: true,", "Computed: true,"])
      .with("optional", () => ["Optional: true,"])
      .otherwise(() => ["Computed: true,"]),
  );

  const tfCustomType = tfAttributeCustomType({ schema, parent, name });
  if (tfCustomType) {
    parts.push(`CustomType: ${tfCustomType},`);
  }

  const tfDefault = tfAttributeDefault({ schema });
  if (tfDefault) {
    parts.push(`Default: ${tfDefault},`);
  }

  const tfValidatorType = tfAttributeValidatorType({ schema });
  if (validators.length > 0) {
    parts.push(`Validators: []${tfValidatorType}{`);
    parts.push(...validators.map((validator) => `${validator},`));
    parts.push(`},`);
  }

  match(schema)
    .with({ type: "object" }, (value) => {
      parts.push("Attributes: map[string]schema.Attribute{");
      parts.push(
        generateSchemaAttributes({
          parent: `${parent}${camelize(name)}`,
          schema: value,
        }),
      );
      parts.push("},");
    })
    .with({ type: "array", items: { type: "object" } }, (value) => {
      parts.push("NestedObject: schema.NestedAttributeObject{");
      parts.push("Attributes: map[string]schema.Attribute{");
      parts.push(
        generateSchemaAttributes({
          parent: `${parent}${camelize(name)}Item`,
          schema: value.items,
        }),
      );
      parts.push("},");
      parts.push("},");
    });

  parts.push(`}`);

  return parts.join("\n");
}

import { camelize, humanize, pluralize, singularize } from "inflection";
import { oas30 } from "openapi3-ts";
import { match } from "ts-pattern";
import type { DataSourceConfig } from "./schema";
import { assertSchemaObject } from "./types";
import { produce } from "immer";
import {
  tfAttributeCustomType,
  tfAttributeValueType,
  tfSchemaAttributeType,
} from "./go-types";

export function generateDataSource({
  swagger,
  config,
}: {
  swagger: oas30.OpenAPIObject;
  config: DataSourceConfig;
}) {
  console.log(`Generating data source: ${config.name}`);

  const isSingle = config.type === "single";

  const schemaKey = isSingle ? config.name : config.resourceName;
  let baseSchema = swagger.components?.schemas?.[schemaKey];
  if (!baseSchema) {
    throw new Error(`Cannot find schema: ${schemaKey} in swagger`);
  }
  assertSchemaObject(baseSchema);

  // Remove creation and update timestamp fields
  baseSchema = produce(baseSchema, (draft) => {
    if (draft.properties) {
      delete draft.properties.created_at;
      delete draft.properties.updated_at;
    }
  });

  const schema = match(config)
    .with(
      { type: "list" },
      (config) =>
        ({
          type: "object",
          properties: {
            [config.name]: {
              type: "array",
              items: {
                ...baseSchema,
                properties: {
                  id: {
                    type: "string",
                    description: `The ID of the ${humanize(singularize(config.name), true)}.`,
                  },
                  ...baseSchema.properties,
                },
                required: ["id", ...(baseSchema.required ?? [])],
              },
              "x-tf-top-level-item-type": true,
            },
          },
        }) satisfies oas30.SchemaObject,
    )
    .with({ type: "single" }, (config) =>
      produce(baseSchema, (draft) => {
        draft.properties = {
          id: {
            type: "string",
            description: `The ID of the ${humanize(config.name, true)}.`,
            "x-tf-computed-optional-required": "required",
          },
          ...draft.properties,
        };
      }),
    )
    .exhaustive();

  const name = `${camelize(config.name)}DataSource`;
  const modelName = `${camelize(config.name)}DataSourceModel`;

  const clientBase = camelize(singularize(config.name));
  const resultVar = isSingle ? "item" : "items";
  const clientMethod = isSingle ? "Get" : "List";
  const clientArgs = isSingle ? ", data.Id.ValueString()" : "";

  return `// Code generated by providergen. DO NOT EDIT.
package provider

import (
	"context"
	"fmt"

	"github.com/hashicorp/terraform-plugin-framework/datasource"
	"github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	"github.com/hashicorp/terraform-plugin-framework/diag"
	"github.com/hashicorp/terraform-plugin-framework/types"
	supertypes "github.com/orange-cloudavenue/terraform-plugin-framework-supertypes"
	"github.com/rootlyhq/terraform-provider-rootly/v5/internal/apiclient"
	"github.com/rootlyhq/terraform-provider-rootly/v5/internal/jsonapitypes"
	"github.com/samber/lo"
)

var _ datasource.DataSource = &${name}{}
var _ datasource.DataSourceWithConfigure = &${name}{}

func New${name}() datasource.DataSource {
  return &${name}{}
}

type ${name} struct {
  baseDataSource
}

func (d *${name}) Metadata(ctx context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
  resp.TypeName = req.ProviderTypeName + "_${config.name}"
}

func (d *${name}) Schema(ctx context.Context, req datasource.SchemaRequest, resp *datasource.SchemaResponse) {
  resp.Schema = schema.Schema{
    MarkdownDescription: ${JSON.stringify(config.description ?? schema.description ?? "")},
    Attributes: map[string]schema.Attribute{
      ${generateSchemaAttributes({ parent: modelName, schema })}
    },
  }
}

func (d *${name}) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
  var data ${modelName}

  resp.Diagnostics.Append(req.Config.Get(ctx, &data)...)
  if resp.Diagnostics.HasError() {
    return
  }

	${resultVar}, err := d.client.${clientBase}${clientMethod}(ctx${clientArgs})
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Unable to read, got error: %s", err))
		return
	} else if ${resultVar} == nil {
		resp.Diagnostics.AddError("Client Error", "Unable to read, got nil response")
		return
	}

	resp.Diagnostics.Append(data.FromApi(ctx, *${resultVar})...)
	if resp.Diagnostics.HasError() {
		return
	}

  resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

${generateModel({
  config,
  schema,
  baseName: camelize(singularize(config.name)),
  name: modelName,
  isTopLevel: true,
})}
`;
}

function generateSchemaAttributes({
  parent,
  schema,
}: {
  parent: string | null;
  schema: oas30.SchemaObject;
}) {
  if (!schema.properties) {
    throw new Error(`Schema does not have properties`);
  }

  const lines: string[] = [];

  for (const [key, value] of Object.entries(schema.properties)) {
    assertSchemaObject(value);
    lines.push(
      `"${key}": ${generateSchemaAttribute({ parent, name: key, schema: value })},`,
    );
  }

  return lines.join("\n");
}

function generateSchemaAttribute({
  parent,
  name,
  schema,
}: {
  parent: string | null;
  name: string;
  schema: oas30.SchemaObject;
}) {
  if (!schema.type) {
    throw new Error(`Schema does not have a type`);
  }

  const tfCustomType = tfAttributeCustomType({ schema, parent, name });

  const parts: string[] = [];
  parts.push(`${tfSchemaAttributeType({ schema })}{`);

  if (schema.description) {
    parts.push(`MarkdownDescription: ${JSON.stringify(schema.description)},`);
  }

  parts.push(
    ...match(schema["x-tf-computed-optional-required"])
      .with("required", () => ["Required: true,"])
      .with("computed", () => ["Computed: true,"])
      .with("computed_optional", () => ["Optional: true,", "Computed: true,"])
      .with("optional", () => ["Optional: true,"])
      .otherwise(() => ["Computed: true,"]),
  );

  if (tfCustomType) {
    parts.push(`CustomType: ${tfCustomType},`);
  }

  match(schema)
    .with({ type: "object" }, (value) => {
      parts.push("Attributes: map[string]schema.Attribute{");
      parts.push(
        generateSchemaAttributes({
          parent: `${parent}${camelize(name)}`,
          schema: value,
        }),
      );
      parts.push("},");
    })
    .with({ type: "array", items: { type: "object" } }, (value) => {
      parts.push("NestedObject: schema.NestedAttributeObject{");
      parts.push("Attributes: map[string]schema.Attribute{");
      parts.push(
        generateSchemaAttributes({
          parent: `${parent}${camelize(name)}Item`,
          schema: value.items,
        }),
      );
      parts.push("},");
      parts.push("},");
    });

  parts.push(`}`);

  return parts.join("\n");
}

function generateModel({
  config,
  schema,
  baseName,
  name,
  isTopLevel,
}: {
  config: DataSourceConfig;
  schema: oas30.SchemaObject;
  baseName: string;
  name: string;
  isTopLevel: boolean;
}) {
  const fromApiDataType =
    config.type === "list" && isTopLevel
      ? `[]apiclient.${baseName}`
      : `apiclient.${baseName}`;
  if (!schema.properties) {
    throw new Error(`Schema ${name} does not have properties`);
  }

  const required = new Set(schema.required);

  const fields: string[] = [];
  const fromApiAssignments: string[] = [];
  const children: string[] = [];

  for (const [key, value] of Object.entries(schema.properties)) {
    assertSchemaObject(value);
    const property = {
      required: required.has(key),
      nullable: value.nullable ?? false,
    };

    // Terraform Attribute
    const goType = tfAttributeValueType({
      schema: value,
      parent: name,
      name: camelize(key),
    });

    if (goType) {
      fields.push(`${camelize(key)} ${goType} \`tfsdk:"${key}"\``);
    } else {
      fields.push(
        `// TODO: Support property ${key} of type ${JSON.stringify(value)}`,
      );
    }

    match(value)
      .with({ type: "object" }, (value) => {
        children.push(
          generateModel({
            config,
            schema: value,
            baseName: `${baseName}${camelize(key)}`,
            name: `${name}${camelize(key)}`,
            isTopLevel: false,
          }),
        );
      })
      .with(
        {
          type: "array",
          items: { type: "object" },
          "x-tf-top-level-item-type": true,
        },
        (value) => {
          children.push(
            generateModel({
              config,
              schema: value.items as oas30.SchemaObject,
              baseName,
              name: `${name}${camelize(key)}Item`,
              isTopLevel: false,
            }),
          );
        },
      )
      .with({ type: "array", items: { type: "object" } }, (value) => {
        children.push(
          generateModel({
            config,
            schema: value.items as oas30.SchemaObject,
            baseName: `${baseName}${camelize(key)}Item`,
            name: `${name}${camelize(key)}Item`,
            isTopLevel: false,
          }),
        );
      });

    // FromApi Assignment
    fromApiAssignments.push(
      match([value, property])
        .with(
          [{ type: "string" }, { nullable: false }],
          () => `m.${camelize(key)} = types.StringValue(data.${camelize(key)})`,
        )
        .with(
          [{ type: "string" }, { nullable: true }],
          () =>
            `m.${camelize(key)} = jsonapitypes.NullableStringValue(data.${camelize(key)})`,
        )
        .with(
          [{ type: "boolean" }, { nullable: false }],
          () => `m.${camelize(key)} = types.BoolValue(data.${camelize(key)})`,
        )
        .with(
          [{ type: "boolean" }, { nullable: true }],
          () =>
            `m.${camelize(key)} = jsonapitypes.NullableBoolValue(data.${camelize(key)})`,
        )
        .with(
          [{ type: "integer" }, { nullable: false }],
          () => `m.${camelize(key)} = types.Int64Value(data.${camelize(key)})`,
        )
        .with(
          [{ type: "integer" }, { nullable: true }],
          () =>
            `m.${camelize(key)} = jsonapitypes.NullableInt64Value(data.${camelize(key)})`,
        )
        .with(
          [{ type: "object" }, { nullable: true }],
          () =>
            `m.${camelize(key)} = (func() supertypes.SingleNestedObjectValueOf[${name}${camelize(key)}] {
  if v, err := data.${camelize(key)}.Get(); err == nil {
    var mm ${name}${camelize(key)}
    diags.Append(mm.FromApi(ctx, v)...)
		return supertypes.NewSingleNestedObjectValueOf[${name}${camelize(key)}](ctx, &mm)
	}
	return supertypes.NewSingleNestedObjectValueOfNull[${name}${camelize(key)}](ctx)
})()`,
        )
        .with(
          [{ type: "array", items: { type: "string" } }, { nullable: true }],
          () =>
            `m.${camelize(key)} = jsonapitypes.NullableListValueOfSlice[string](ctx, data.${camelize(key)})`,
        )
        .with(
          [{ type: "array", items: { type: "integer" } }, { nullable: true }],
          () =>
            `m.${camelize(key)} = jsonapitypes.NullableListValueOfSlice[int64](ctx, data.${camelize(key)})`,
        )
        .with(
          [
            {
              type: "array",
              items: { type: "object" },
              "x-tf-top-level-item-type": true,
            },
            { nullable: false },
          ],
          () => `m.${camelize(key)} = (func() supertypes.ListNestedObjectValueOf[${name}${camelize(key)}Item] {
  return supertypes.NewListNestedObjectValueOfValueSlice[${name}${camelize(key)}Item](ctx, lo.Map(data, func(vv apiclient.${baseName}, _ int) ${name}${camelize(key)}Item {
    var mm ${name}${camelize(key)}Item
    diags.Append(mm.FromApi(ctx, vv)...)
    return mm
  }))
})()`,
        )
        .with(
          [{ type: "array", items: { type: "object" } }, { nullable: true }],
          () => `m.${camelize(key)} = (func() supertypes.ListNestedObjectValueOf[${name}${camelize(key)}Item] {
  if v, err := data.${camelize(key)}.Get(); err == nil {
    return supertypes.NewListNestedObjectValueOfValueSlice[${name}${camelize(key)}Item](ctx, lo.Map(v, func(vv apiclient.${baseName}${camelize(key)}Item, _ int) ${name}${camelize(key)}Item {
      var mm ${name}${camelize(key)}Item
      diags.Append(mm.FromApi(ctx, vv)...)
      return mm
    }))
  }
  return supertypes.NewListNestedObjectValueOfNull[${name}${camelize(key)}Item](ctx)
})()`,
        )
        .otherwise(
          () =>
            `// TODO: Implement FromApi for ${key} of type ${JSON.stringify(value)} and property ${JSON.stringify(property)}`,
        ),
    );
  }

  return `
type ${name} struct {
${fields.join("\n")}
}

func (m *${name}) FromApi(ctx context.Context, data ${fromApiDataType}) diag.Diagnostics {
	var diags diag.Diagnostics

	${fromApiAssignments.join("\n")}

	return diags
}

${children.join("\n\n")}
`;
}
